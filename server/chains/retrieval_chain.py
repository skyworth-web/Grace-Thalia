def build_retriever(k: int = 5):
    """Provide a raw retriever."""
    if not os.path.exists(CHROMA_DIR):
        raise ValueError("Vector store missing — run /ingest first.")

    chroma = Chroma(embedding_function=get_embed_model(), persist_directory=CHROMA_DIR)
    return chroma.as_retriever(search_kwargs={"k": k})


# ============================================================
# 5) HELPER: RESUME SUMMARY EXTRACTOR
# ============================================================
def _extract_resume_summary(resume_text: str) -> str:
    """
    Extract structured summary using GPT-4o.
    """
    try:
        llm = ChatOpenAI(model="gpt-4o", temperature=0.1)
        prompt = PromptTemplate(
            input_variables=["resume"],
            template="""Extract detailed structured resume info.

Resume:
{resume}

Return a structured summary including:
- personal info
- experience
- skills
- projects
- education
""",
        )
        chain = prompt | llm
        out = chain.invoke({"resume": resume_text})
        return out.content if hasattr(out, "content") else str(out)

    except Exception as e:
        logger.warning("⚠ Resume summary extraction failed:", e)
        return resume_text[:400]
