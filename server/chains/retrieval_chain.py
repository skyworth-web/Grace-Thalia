# server/chains/retrieval_chain.py

import os
import logging
from datetime import datetime

from langchain_openai import OpenAIEmbeddings, ChatOpenAI
from langchain_chroma import Chroma
from langchain_text_splitters import RecursiveCharacterTextSplitter

from langchain_core.prompts import PromptTemplate
from langchain_core.runnables import RunnableMap, RunnableLambda
from langchain_core.output_parsers import StrOutputParser
from operator import itemgetter

logger = logging.getLogger(__name__)

DATA_DIR = os.path.join(os.path.dirname(__file__), "..", "data")
CHROMA_DIR = os.path.join(DATA_DIR, "chroma")

# Lazy initialization of embedding model (only when needed, after API key is set)
_EMBED_MODEL = None
_TEXT_SPLITTER = None

def get_embed_model():
    """Get or create the embedding model (lazy initialization)."""
    global _EMBED_MODEL
    if _EMBED_MODEL is None:
        # Check if API key is set
        if not os.getenv("OPENAI_API_KEY"):
            raise ValueError("OPENAI_API_KEY must be set before using embeddings")
        _EMBED_MODEL = OpenAIEmbeddings(model="text-embedding-3-small")
    return _EMBED_MODEL

def get_text_splitter():
    """Get or create the text splitter (cached for performance)."""
    global _TEXT_SPLITTER
    if _TEXT_SPLITTER is None:
        _TEXT_SPLITTER = RecursiveCharacterTextSplitter(chunk_size=350, chunk_overlap=50)
    return _TEXT_SPLITTER


# ============================================================
# 1) INGEST RESUME + JOB DOCUMENTS
# ============================================================
def ingest_docs() -> None:
    """
    Clears old vector DB, then ingests:
      - resume.txt
      - job.txt
      - autogenerated resume summary
    """
    os.makedirs(DATA_DIR, exist_ok=True)

    # Clear vector store
    import shutil
    if os.path.exists(CHROMA_DIR):
        shutil.rmtree(CHROMA_DIR)
    os.makedirs(CHROMA_DIR, exist_ok=True)

    chroma = Chroma(embedding_function=get_embed_model(), persist_directory=CHROMA_DIR)
    # Use different chunk size for resume/job (larger chunks for better context)
    splitter = RecursiveCharacterTextSplitter(chunk_size=800, chunk_overlap=300)

    docs = []

    # Ingest resume
    resume_path = os.path.join(DATA_DIR, "resume.txt")
    resume_summary = None

    if os.path.exists(resume_path):
        with open(resume_path, "r", encoding="utf-8") as f:
            text = f.read().strip()

        if text:
            resume_summary = _extract_resume_summary(text)

            # Chunk full resume
            for chunk in splitter.create_documents([text]):
                chunk.metadata = {
                    "source": "resume",
                    "type": "resume",
                }
                docs.append(chunk)

            # Add structured summary chunk
            if resume_summary:
                from langchain_core.documents import Document

                docs.append(
                    Document(
                        page_content=f"RESUME SUMMARY:\n{resume_summary}",
                        metadata={"source": "resume_summary", "type": "summary"}
                    )
                )

    # Ingest job description
    job_path = os.path.join(DATA_DIR, "job.txt")
    if os.path.exists(job_path):
        with open(job_path, "r", encoding="utf-8") as f:
            text = f.read().strip()
        if text:
            for chunk in splitter.create_documents([text]):
                chunk.metadata = {"source": "job", "type": "job"}
                docs.append(chunk)

    if not docs:
        logger.warning("⚠ No resume/job documents found during ingestion.")
        return

    chroma.add_documents(docs)
    logger.info(f"✅ Ingestion complete ({len(docs)} chunks)")


