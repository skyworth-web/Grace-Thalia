# 3) BUILD BASIC RETRIEVAL CHAIN (Legacy)
# ============================================================
def build_chain():
    """
    Original retrieval chain used for /generate (non-stream).
    Now supports searching full vector DB (resume + job + transcript).
    """
    if not os.path.exists(CHROMA_DIR):
        raise ValueError("Vector store missing — run /ingest first.")

    chroma = Chroma(embedding_function=get_embed_model(), persist_directory=CHROMA_DIR)
    retriever = chroma.as_retriever(search_kwargs={"k": 6})

    llm = ChatOpenAI(model="gpt-4o", temperature=0.3)

    prompt = PromptTemplate(
        input_variables=["context", "question", "chat_history"],
        template="""
You are an expert interview answer assistant.

### CONTEXT (Resume + Job + Transcript):
{context}

### Previous conversation:
{chat_history}

### Interview Question:
{question}

Generate a clear, natural 2–4 sentence answer using:
- the transcript context (conversation with HR)
- the resume experience
- relevant job requirements
""",
    )

    chain = (
        RunnableMap({
            "context": itemgetter("question") | retriever,
            "question": itemgetter("question"),
            "chat_history": itemgetter("chat_history"),
        })
        | prompt
        | llm
        | StrOutputParser()
    )

    chain = chain | RunnableLambda(lambda t: {"answer": t})
    logger.info("✅ Retrieval chain ready (resume + job + transcript)")
    return chain


